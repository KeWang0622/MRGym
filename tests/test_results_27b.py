"""The report of the first 27B training runs, the figure of the front page and the generated blocks of README.md and
docs/RECIPE.md are what docs/experiments/27b/report.py writes from the stored result files; the recipe's settings
file is one the node scripts accept."""
import copy
import gzip
import importlib.util
import json
import os
import re
import subprocess
import sys

import pytest

from mrgym import learn

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
SCRIPT = os.path.join(ROOT, "docs", "experiments", "27b", "report.py")
RECIPE = os.path.join(ROOT, "recipes", "qwen3.8-27b-nowrap.env")
MAKE_MAIN = os.path.join(ROOT, "integrations", "verl", "node", "make_main.sh")


def _read(*parts):
    with open(os.path.join(ROOT, *parts), encoding="utf-8") as f:
        return f.read()


def _block(text, name):
    m = re.search(rf"<!-- {name}:START -->\n(.*?)<!-- {name}:END -->", text, re.S)
    assert m, f"no {name} block"
    return m.group(1)


@pytest.fixture(scope="module")
def report():
    if not os.path.exists(SCRIPT):
        pytest.skip("the tests are not running from a checkout of the repository")
    spec = importlib.util.spec_from_file_location("report_27b", SCRIPT)
    module = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(module)
    return module


@pytest.fixture(scope="module")
def stored(report):
    return report.stored()


def test_the_stored_report_is_current_and_names_nothing_outside_the_repository():
    run = subprocess.run([sys.executable, SCRIPT, "--check"], capture_output=True, text=True, cwd=ROOT)
    assert run.returncode == 0, run.stdout + run.stderr
    text = _read("docs", "experiments", "RESULTS-27b.md")
    assert text.startswith("<!-- Generated by docs/experiments/27b/report.py")
    assert '"it trained" by that rule: **False**' in text                          # one trained environment is not the plan's success
    for page in (text, _read("README.md"), _read("docs", "RECIPE.md"), _read("recipes", "qwen3.8-27b-nowrap.env"), _read("assets", "training_27b.json")):
        assert "s3:" + "//" not in page and "/opt" + "/" not in page and "/mnt" + "/" not in page      # run ids only: no store, no machine path


def test_the_before_after_table_of_the_front_page_is_counted_from_the_logs(report, stored):
    """Passes and episodes of every row, counted here from the stored files without the report's own functions."""
    def counts(name):
        out = {}
        with gzip.open(os.path.join(ROOT, "docs", "experiments", "27b", "results", name), "rt", encoding="utf-8") as f:
            for line in f:
                r = json.loads(line)
                k = (r["env_id"].split("/")[1], r["level"])
                out[k] = (out.get(k, (0, 0))[0] + bool(r["passed"]), out.get(k, (0, 0))[1] + 1)
        return out
    base, trained = counts("test_base_57k.jsonl.gz"), counts("test_trained_step60.jsonl.gz")
    readme, recipe = _read("README.md"), _read("docs", "RECIPE.md")
    block = _block(readme, "TRAINING")
    rows = [ln for ln in block.splitlines() if ln.startswith("| ") and "`" in ln]
    assert len(rows) == len(base) == 4
    for (env, level), (k, n) in base.items():
        row = next(ln for ln in rows if f"`{env} L{level}`" in ln)
        t = trained[(env, level)]
        assert f"({k} / {n})" in row.split(" | ")[1] and f"({t[0]} / {t[1]})" in row.split(" | ")[2], row
    assert [ln.split(" · ")[0].lstrip("| ") for ln in rows] == [report.PLAIN[k][1] for k in sorted(report.PLAIN)]
    assert "one run, one seed" in block and "exploratory" in block and "(docs/experiments/RESULTS-27b.md)" in block
    assert 'src="assets/training_27b.png"' in block and 'src="../assets/training_27b.png"' in _block(recipe, "TRAINING")
    # the same table on the recipe page; only the links differ
    assert [ln for ln in _block(recipe, "TRAINING").splitlines() if ln.startswith("|")] == [ln for ln in block.splitlines() if ln.startswith("|")]
    for rel, (old, new) in report.pages(stored).items():
        assert old == new, f"{rel}: a generated block is stale; run docs/experiments/27b/report.py"


def test_the_figure_is_drawn_from_its_stored_data_file(report, stored):
    data = json.loads(_read("assets", "training_27b.json"))
    assert data == report.figure_data(stored) and data["version"] == report.FIGURE_VERSION
    assert [c["label"] for c in data["secret"]] == ["trained level", "harder level", "never-trained level", "another task family (never trained)"]
    assert all(0 <= c[s]["lo"] <= c[s]["rate"] <= c[s]["hi"] <= 1 for c in data["secret"] for s in ("before", "after"))
    assert [s["run"] for s in data["dev"]] == ["v07", "v07"] and data["second"]["run"] == "v09"
    assert data["dev"][0]["points"][0]["step"] == 0 and data["dev"][0]["points"][-1]["step"] == data["steps"] == 60
    path = os.path.join(ROOT, "assets", "training_27b.png")
    with open(path, "rb") as f:
        assert f.read(8) == b"\x89PNG\r\n\x1a\n"
    assert os.path.getsize(path) < 200 * 1024


def test_check_fails_when_a_stored_result_changes(report, stored):
    """One more passing episode in the final readout: the report, the figure's data and both pages are stale."""
    assert report.stale(stored, report.build(stored)) == []
    changed = dict(stored, t60=copy.deepcopy(stored["t60"]))
    row = next(r for r in changed["t60"] if not r["passed"])
    row.update(passed=True, outcome="pass")
    stale = report.stale(changed, report.build(changed))
    assert stale[0] == "docs/experiments/RESULTS-27b.md" and stale[1].startswith("assets/training_27b.png")
    assert stale[2:] == ["README.md", "docs/RECIPE.md"]
    # a change of the drawing alone makes the figure stale, nothing else
    version = report.FIGURE_VERSION
    try:
        report.FIGURE_VERSION = version + 1
        assert report.stale(stored, report.build(stored)) == ["assets/training_27b.png (its data, assets/training_27b.json)"]
    finally:
        report.FIGURE_VERSION = version


def test_the_recipe_line_follows_the_run_list(report, stored):
    """Which commit the recipe ran on, and the state of its check on the current code, come from runs.json; when the
    log of the check arrives the line shows its newest evaluation."""
    runs = stored["runs"]
    line = report.status_block(stored)
    assert runs["v07"]["code"] in line and runs["v17"]["code"] in line and runs["v17"]["state"].split(";")[0] in line
    assert _block(_read("README.md"), "RECIPE_STATUS").strip() == line == _block(_read("docs", "RECIPE.md"), "RECIPE_STATUS").strip()
    later = dict(stored, runs=dict(runs, v17=dict(runs["v17"], state="training")), logs=dict(stored["logs"], v17=stored["logs"]["v09"]))
    line = report.status_block(later)
    assert "): training. Its newest evaluation on public instances (step 40): NoWrap-v1 L1 27 / 32" in line
    assert "README.md" in report.stale(later, report.build(later))


def test_the_recipe_file_is_one_the_node_scripts_accept(report, tmp_path):
    env = report.settings(RECIPE)
    expected = dict(MODEL_HF="Qwen/Qwen3.8-27B", MODEL_NAME="policy", TOOL_FORMAT="qwen3_coder", CHAT_KWARGS="enable_thinking=False",
                    TRAIN_ARMS="Scanner/NoWrap-v1:1,2", DEV_ARMS="Scanner/NoWrap-v1:1,2,3", DEV_SEEDS="0-31", VAL_N="2",
                    TEST_ARMS="Scanner/NoWrap-v1:1,2,3 Scanner/NullTissue-v0:0", TEST_SEEDS="0-47", UNTRAINED="Scanner/NullTissue-v0",
                    ROLLOUT_TP="4", GPU_MEM_UTIL="0.60", MAX_PROMPT_LEN="8192", MAX_RESPONSE_LEN="49152", MAX_TOKENS_PER_TURN="2048",
                    TOKENS_PER_GPU="59392", LORA_RANK="32", LORA_ALPHA="64", LR="1e-5", WARMUP_STEPS="5", KL_COEF="0", PROMPTS_PER_STEP="8",
                    GROUP_SIZE="8", TOTAL_STEPS="60", SAVE_FREQ="5", TEST_FREQ="10", SIGNAL="pass", CURRICULUM_MODE="bandit", CUT_MAX="0.50",
                    MIN_ENVS="1", SUBMIT_MIN="0.40", MIXED_MIN="0.30", BASE_RATE="0.30")
    assert {k: env[k] for k in expected} == expected                                # the settings of the run that checks the recipe
    assert int(env["TOKENS_PER_GPU"]) == int(env["MAX_PROMPT_LEN"]) + int(env["MAX_RESPONSE_LEN"]) + 2048
    fill = {k for k, v in env.items() if v.startswith("FILL_IN")}
    assert fill == {"RUN_ID", "OUT_URI", "REPO_SRC", "SECRET_URI"}                  # the launcher's four lines, and nothing of ours in them
    # every variable is one the node scripts read
    scripts = "".join(_read("integrations", "verl", *p) for p in (("node", "train.sh"), ("node", "calibrate.sh"), ("node", "lib.sh"),
                                                                  ("overrides.sh",), ("launch.sh",)))
    assert not [k for k in env if not re.search(rf"\b{k}\b", scripts)]
    # the run list and the settings block say the same
    node = report.stored()["runs"]["v17"]["node"]
    assert f"{int(env['MAX_PROMPT_LEN']):,} + {int(env['MAX_RESPONSE_LEN']):,} tokens" in node
    block = _block(_read("README.md"), "RECIPE_SETTINGS")
    assert block == _block(_read("docs", "RECIPE.md"), "RECIPE_SETTINGS").replace("](../recipes/", "](recipes/")
    for k in ("MODEL_HF", "TRAIN_ARMS", "TEST_ARMS", "LR", "LORA_RANK"):
        assert env[k] in block
    # make_main.sh writes a job script from it, and bash reads the values this test read
    out = tmp_path / "job.sh"
    run = subprocess.run(["bash", MAKE_MAIN, "train", RECIPE, str(out)], capture_output=True, text=True)
    assert run.returncode == 0, run.stdout + run.stderr
    assert f"{len(env)} parameter(s)" in run.stdout
    exports = [ln for ln in out.read_text(encoding="utf-8").splitlines() if ln.startswith("export ")][:len(env)]
    names = [ln.split("=", 1)[0].split()[1] for ln in exports]
    assert names == list(env)
    show = subprocess.run(["bash", "-c", "\n".join(exports) + "\n" + "\n".join(f'printf "%s\\n" "${k}"' for k in names)], capture_output=True, text=True)
    assert show.returncode == 0 and show.stdout.splitlines() == [env[k] for k in names], show.stderr
    # the same file with another run id is accepted for the calibration
    assert subprocess.run(["bash", MAKE_MAIN, "calibrate", RECIPE, str(tmp_path / "cal.sh")], capture_output=True, text=True).returncode == 0
    missing = tmp_path / "no_run_id.env"
    missing.write_text("".join(ln for ln in _read("recipes", "qwen3.8-27b-nowrap.env").splitlines(True) if not ln.startswith("RUN_ID=")), encoding="utf-8")
    assert subprocess.run(["bash", MAKE_MAIN, "train", str(missing), str(tmp_path / "x.sh")], capture_output=True, text=True).returncode == 2


def test_the_front_page_says_what_it_is_before_it_shows_training_and_keeps_every_generated_block():
    readme, recipe = _read("README.md"), _read("docs", "RECIPE.md")
    order = [readme.index(h) for h in ('<img src="assets/hero.png"', "## What it is", "## Try it", "## The tasks",
                                       "## Does training on it work?", "## The recipe")]
    assert order == sorted(order)                       # the scanner and what it does first, the training result and the recipe after
    top = readme[:order[-1]]
    lines_before_training = readme[:order[4]].count("\n")
    assert lines_before_training <= 150, f"{lines_before_training} lines before the training result"
    assert "mrgym demo" in readme[order[2]:order[3]] and "import mrgym" in readme[order[2]:order[3]]
    tail = readme[order[-1]:]
    assert "(docs/RECIPE.md)" in tail
    for name in ("RECIPE_SETTINGS", "RECIPE_STATUS"):
        assert f"<!-- {name}:START -->" in tail
    assert "<!-- TRAINING:START -->" in readme[order[4]:order[5]]
    for name in ("COUNTS", "DEMO", "ENVS", "RESULTS", "TIMING"):
        assert f"<!-- {name}:START -->" in readme
    assert readme.count("<details>") == readme.count("</details>") >= 8
    top = readme
    lo, hi = (round(100 * x) for x in learn.ENTRY_BAND)
    assert f"{lo}-{hi} %" in top and f"{lo}-{hi} %" in _block(recipe, "RECIPE_PITFALLS")       # the band of mrgym.learn, not a typed one
    assert len(recipe.rstrip("\n").split("\n")) <= 120
    assert "RECIPE.md" in _read("docs", "README.md")
