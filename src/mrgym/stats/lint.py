"""The reporting rules, as checks. ``mrgym results --check`` and ``tools/generate.py --check`` run them.

``lint_results(summary)`` reads a ``results.json`` (schema ``mrgym-results/2``); ``lint_text(text)`` reads hand-written
Markdown. Text between generator markers (``<!-- NAME:START -->`` ... ``<!-- NAME:END -->``), inside a
``<!-- STAT:key -->...<!-- /STAT -->`` span, in a fenced code block, in inline code or in a file that starts with a
``<!-- Generated by`` comment is produced from stored results and is trusted; everything else is scanned.

    R1   a rate has n and an interval           R7   pilot rows stay pilot
    R2   the unit is the instance               R8   floors and the oracle stand beside the models
    R3   no cross-cell claim without its test   R9   no rate on a subset chosen by outcome
    R4   seeds listed, one seed set per table   R10  losses to infrastructure are visible and small
    R5   exact command and settings as sent     R11  the analysis plan comes first
    R6   certainty is bounded                   R12  cost beside accuracy
    R13  a published record is checkable (stored conversation, deliverable, outcome, harness id)
    D1   a published row meets the design (300 instances per environment; 2 episodes per instance for a model)

R13 and D1 extend the twelve rules of the statistics specification with the record fields of the learnability
specification and the published minimum of the baseline design.

Each violation is ``{"rule", "line", "where", "message"}``; ``line`` is 1-based (for a JSON file, the line on which
the offending row starts when the file is written with ``indent=1``).
"""
from __future__ import annotations

import re

RULES = {
    "R1": "a rate has n and an interval", "R2": "the unit is the instance", "R3": "no cross-cell claim without a paired test",
    "R4": "seeds listed", "R5": "exact command", "R6": "certainty is bounded", "R7": "pilot rows stay pilot",
    "R8": "floors and oracle present", "R9": "no selection", "R10": "losses are visible", "R11": "plan first",
    "R12": "cost beside accuracy", "R13": "records are checkable", "D1": "published minimum of the design",
}
CLUSTERED = ("wilson-kg-t", "beta-binomial-grid")
SELECTED_SUBSETS = ("admitted", "admitted-only", "valid", "valid-only", "best-of-k", "best-checkpoint", "best-run")
MIN_INSTANCES, MIN_EPISODES, PILOT_BELOW, MAX_INFRA = 300, 2, 100, 0.02

# ------------------------------------------------------------------ text
RATE = re.compile(r"\d+(?:\.\d+)?\s?%|\b\d+\s?/\s?\d+\b|\b\d+ of \d+\b")
RESULT_WORD = re.compile(r"\b(pass(?:es|ed)?|pass rate|success rate|solve[sd]?|succeed(?:s|ed)?|fail(?:s|ed)?|admit(?:s|ted)?|scor(?:es|ed))\b", re.I)
SUBJECT = re.compile(r"\b(reference|polic(?:y|ies)|models?|agents?|recipe|constant|baseline|shortcut|sweep|ablation)\b", re.I)
RULE_WORD = re.compile(r"\b(at least|at most|no more than|must|should|shall|needs?|has to|have to|required?|requires|threshold|if|unless|"
                       r"iff|rule)\b|[≥≤]|>=|<=", re.I)                 # a sentence that states a rule, not a result
COMPARATIVE = re.compile(r"\b(better|worse|ahead|outperform(?:s|ed)?|harder|easier|rank(?:s|ed)?|beats?)\b|"
                         r"\b(?:above|below)\s+(?!for\b|and\b|or\b|are\b|is\b|in\b|on\b|shows?\b|lists?\b)[\w`]", re.I)   # not "see below"
CERTAIN = re.compile(r"\b100\s?%|(?<![\d.])0\s?%|\b(always|never|all|none)\b", re.I)
BOUNDED = re.compile(r"\bbounds?\b|one-sided|[≥≤]|>=|<=", re.I)
SELECTION = re.compile(r"\b(admitted[- ]only|admitted instances|valid[- ]only|valid deliverables only|best[- ]of[- ](?:\d+|k|several)|"
                       r"best checkpoint|best run|instances (?:it|they) (?:solved|passed))\b", re.I)
FULL_SET = re.compile(r"\b(full set|all instances|every instance|of all)\b", re.I)
STATE_CLAIMS = (
    ("R1", re.compile(r"\bno (?:language |open |open-weights? )?models? (?:has|have|was|were) (?:yet )?(?:been )?run\b", re.I),
     "a statement about which agents were run is a result: generate it from results.json"),
)
SAME_INSTANCES = re.compile(r"\b(?:every|each|all) (?:agents?|models?|rows?|polic(?:y|ies)) (?:plays?|played|uses?|used|runs?|ran|sees?|saw|shares?|shared)\b"
                            r"[^.]*\bthe same (?:instances|seeds)\b", re.I)
ENTITY_LEVEL = re.compile(r"\blevels? (\d+)\b", re.I)
ENTITY_ENV = re.compile(r"\b(?:[A-Z][A-Za-z0-9]*/)?([A-Z][A-Za-z0-9]*)-v\d+\b")
CMP = re.compile(r"<!--\s*CMP:([^\s>]+)\s*-->")
_BLOCK = re.compile(r"<!-- ([A-Z_]+):START -->.*?<!-- \1:END -->", re.S)
_STAT = re.compile(r"<!--\s*STAT:[^>]*-->.*?<!--\s*/STAT\s*-->", re.S)
_FENCE = re.compile(r"^(```|~~~).*?^\1[ \t]*$", re.S | re.M)
_CODE = re.compile(r"`[^`\n]*`")
_COMMENT = re.compile(r"<!--(?!\s*CMP:).*?-->", re.S)


def _blank(match: re.Match, keep: str = "") -> str:
    """The matched text replaced by spaces, line breaks kept, so that offsets and line numbers do not move."""
    text = re.sub(r"[^\n]", " ", match.group(0))
    return keep + text[len(keep):] if keep and len(text) >= len(keep) and "\n" not in text[:len(keep)] else text


def scannable(text: str) -> str:
    """``text`` with every trusted region blanked: generator blocks, fenced code, STAT spans (replaced by the token
    STAT), inline code (replaced by the token CODE where it fits) and comments other than CMP markers."""
    if text.lstrip().startswith("<!-- Generated by"):
        return re.sub(r"[^\n]", " ", text)
    text = _BLOCK.sub(_blank, text)
    text = _FENCE.sub(_blank, text)
    text = _STAT.sub(lambda m: _blank(m, "STAT"), text)
    text = _CODE.sub(_blank, text)
    return _COMMENT.sub(_blank, text)


def sentences(text: str):
    """(line number, sentence) of a Markdown text: table rows and list items are one unit each, paragraphs are split
    at sentence ends. Line numbers are those of the first character."""
    lines = text.split("\n")
    i = 0
    while i < len(lines):
        if not lines[i].strip():
            i += 1
            continue
        if re.match(r"\s*(\||[-*+] |\d+\. |#)", lines[i]):
            start, unit = i, lines[i]
            i += 1
            while i < len(lines) and lines[i].strip() and re.match(r"\s{2,}\S", lines[i]) and not re.match(r"\s*(\||[-*+] |\d+\. )", lines[i]):
                unit += " " + lines[i].strip()
                i += 1
            yield start + 1, unit
            continue
        start, chunk = i, []
        while i < len(lines) and lines[i].strip() and not re.match(r"\s*(\||[-*+] |\d+\. |#)", lines[i]):
            chunk.append(lines[i])
            i += 1
        para, offsets, pos = "", [], 0
        for k, ln in enumerate(chunk):
            offsets.append((pos, start + k + 1))
            para += ln + " "
            pos = len(para)
        for m in re.finditer(r"[^.!?]*(?:[.!?](?!\s)[^.!?]*)*[.!?]?(?:\s+|$)", para):
            s = m.group(0).strip()
            if s:
                first = m.start() + len(m.group(0)) - len(m.group(0).lstrip())
                yield max(line for off, line in offsets if off <= first), s


def _entities(sentence: str, names) -> set:
    found = {f"level {m}" for m in ENTITY_LEVEL.findall(sentence)}
    found |= {m for m in ENTITY_ENV.findall(sentence)}
    low = sentence.lower()
    found |= {n for n in names if re.search(rf"(?<![\w-]){re.escape(n.lower())}(?![\w-])", low)}
    return found


def lint_text(text: str, summary: dict | None = None, names=()) -> list[dict]:
    """Violations of the text rules (R1, R3, R4, R6, R9) in hand-written Markdown. ``summary`` is the results the text
    talks about (agent names, comparisons, seed sets); ``names`` are further agent names to recognise."""
    summary = summary or {}
    agents = {a for kind in (summary.get("agents") or {}).values() for a in kind} | set(names)
    short = {ENTITY_ENV.match(e).group(1) for e in (summary.get("environments") or {}) if ENTITY_ENV.match(e)}
    comps = {c["id"]: c for c in summary.get("comparisons") or []}
    out = []

    def add(rule, line, message):
        out.append(dict(rule=rule, line=line, where="text", message=message))

    for line, s in sentences(scannable(text)):
        plain = CMP.sub("", s)
        has_rate = bool(RATE.search(plain))
        about = bool(RESULT_WORD.search(plain)) and bool(SUBJECT.search(plain) or _entities(plain, agents))
        is_rule = bool(RULE_WORD.search(plain))
        if has_rate and about and not is_rule:
            add("R1", line, f"a rate typed by hand ({RATE.search(plain).group(0).strip()}): put it in a generated block or a "
                            "<!-- STAT:key --> span so that it carries n and its interval")
        for rule, pattern, message in STATE_CLAIMS:
            if pattern.search(plain):
                add(rule, line, message)
        if SAME_INSTANCES.search(plain):
            hashes = {}
            for r in summary.get("rows") or []:
                hashes.setdefault((r["env_id"], r.get("tier")), set()).add(r.get("seed_set_sha256"))
            if not hashes or any(len(h) > 1 for h in hashes.values()):
                add("R4", line, "claims that every agent plays the same instances, but the rows of a table have different seed sets"
                                if hashes else "claims that every agent plays the same instances; no results support it")
        word = COMPARATIVE.search(plain)
        if word:
            ents = _entities(plain, agents | short)
            if len(ents) >= 2:
                ids = CMP.findall(s)
                ok = bool(ids) and all(i in comps and comps[i].get("p_holm") is not None and comps[i]["p_holm"] < 0.05 for i in ids)
                if not ok:
                    add("R3", line, f"'{word.group(0).split()[0]}' between {', '.join(sorted(ents))} without a planned paired comparison "
                                    "(<!-- CMP:id --> with p_holm < 0.05 in comparisons[])")
        if CERTAIN.search(plain) and about and not is_rule and not BOUNDED.search(plain) and "STAT" not in plain:
            add("R6", line, f"'{CERTAIN.search(plain).group(0).strip()}' about a rate without the one-sided bound beside it")
        if SELECTION.search(plain) and (has_rate or "STAT" in plain) and not FULL_SET.search(plain):
            add("R9", line, f"a rate on a subset chosen by outcome ('{SELECTION.search(plain).group(0)}') without the full-set rate beside it")
    return out


# ------------------------------------------------------------------ results.json
def locate(text: str, where: str) -> int:
    """Line of ``rows[i]`` or ``comparisons[i]`` in a JSON text written with ``indent=1`` (1 when it cannot be found)."""
    m = re.fullmatch(r"(\w+)\[(\d+)\]", where or "")
    if not m or not text:
        return 1
    lines = text.split("\n")
    try:
        start = next(i for i, ln in enumerate(lines) if ln.startswith(f' "{m[1]}": ['))
    except StopIteration:
        return 1
    count = -1
    for i in range(start + 1, len(lines)):
        if lines[i] == "  {":
            count += 1
            if count == int(m[2]):
                return i + 1
        elif lines[i].startswith(" ]"):
            break
    return start + 1


def lint_results(summary: dict, text: str = "") -> list[dict]:
    """Violations of the reporting rules in a ``results.json`` dict. ``text`` is the file's text, for line numbers.
    Only published rows are held to the rules; a pilot row is checked for staying pilot (R7)."""
    out = []

    def add(rule, where, message):
        out.append(dict(rule=rule, line=locate(text, where), where=where, message=message))

    rows = summary.get("rows") or []
    published = [(i, r) for i, r in enumerate(rows) if r.get("tier") == "published"]
    tiers = {(r["env_id"], r["agent"]): r for r in rows}
    plan, plan_sha = summary.get("plan"), summary.get("plan_sha256")
    for i, r in published:
        where, name = f"rows[{i}]", f"{r.get('env_id')} / {r.get('agent')}"
        model = r.get("kind") != "scripted"
        lacking = [k for k in ("instances", "episodes", "pass_ci95", "ci_method") if r.get(k) is None]
        if lacking:
            add("R1", where, f"{name}: a rate without {', '.join(lacking)}")
        if (r.get("episodes") or 0) > (r.get("instances") or 0) and r.get("ci_method") not in CLUSTERED:
            add("R2", where, f"{name}: {r.get('episodes')} episodes on {r.get('instances')} instances with the interval '{r.get('ci_method')}', which is not clustered")
        if r.get("n_eff") is not None and r.get("episodes") is not None and r["n_eff"] > r["episodes"] + 1e-6:
            add("R2", where, f"{name}: n_eff {r['n_eff']} exceeds the {r['episodes']} episodes")
        lacking = [k for k in ("seeds", "split", "seed_set_sha256") if not r.get(k)]
        if lacking:
            add("R4", where, f"{name}: no {', '.join(lacking)}")
        lacking = [k for k in ("command", "package_version", "engine", "utc") if not r.get(k)]
        if model:
            lacking += [k for k in ("model", "provider") if not r.get(k)]
            sampling = r.get("sampling") or {}
            lacking += [f"{k} as sent" for k in ("temperature", "max_tokens", "max_turns") if sampling.get(k) is None or sampling.get(k) == "mixed"]
        if lacking:
            add("R5", where, f"{name}: no {', '.join(lacking)}")
        if r.get("pass_rate") in (0, 1, 0.0, 1.0) and r.get("one_sided_bound") is None:
            add("R6", where, f"{name}: a rate of {100 * r['pass_rate']:.0f} % without its one-sided bound")
        if r.get("subset") in SELECTED_SUBSETS and r.get("full_set_rate") is None:
            add("R9", where, f"{name}: a rate on the subset '{r['subset']}', chosen by outcome, without the full-set rate")
        if (r.get("infra_error_rate") or 0) > MAX_INFRA:
            add("R10", where, f"{name}: {100 * r['infra_error_rate']:.1f} % of the episodes were lost to infrastructure errors (limit {100 * MAX_INFRA:.0f} %)")
        if plan_sha is not None and r.get("plan_sha256") != plan_sha:
            add("R11", where, f"{name}: its records were not played under the registered analysis plan")
        if plan and r.get("utc") and plan.get("registered_utc") and r["utc"][0] < plan["registered_utc"]:
            add("R11", where, f"{name}: a record ({r['utc'][0]}) is older than the plan ({plan['registered_utc']})")
        if model and any(r.get(k) is None for k in ("tokens_in_total", "tokens_out_total", "wall_s_total")):
            add("R12", where, f"{name}: a model row without token totals and wall time")
        if r.get("records_missing"):
            add("R13", where, f"{name}: records lack " + ", ".join(f"{k} ({n})" for k, n in r["records_missing"].items()))
        elif model and (r.get("transcripts") or 0) < (r.get("episodes") or 0):
            add("R13", where, f"{name}: {r.get('transcripts')} stored conversations for {r.get('episodes')} episodes")
        if (r.get("instances") or 0) < MIN_INSTANCES:
            add("D1", where, f"{name}: {r.get('instances')} instances; a published row needs {MIN_INSTANCES} per environment")
        if model and (r.get("episodes_per_instance") or [0])[0] < MIN_EPISODES:
            add("D1", where, f"{name}: fewer than {MIN_EPISODES} episodes on some instance")
        design = ((plan or {}).get("design") or {}).get("seed_set_sha256") or {}
        if design.get(r.get("env_id")) and r.get("seed_set_sha256") and r["seed_set_sha256"] != design[r["env_id"]] and not r.get("subset"):
            add("R4", where, f"{name}: its seed set is not the one registered in the analysis plan")
    for env_id in sorted({r["env_id"] for _, r in published}):
        part = [(i, r) for i, r in published if r["env_id"] == env_id]
        hashes = {r.get("seed_set_sha256") for _, r in part if not r.get("subset")}
        if len(hashes) > 1:
            common = max(hashes, key=lambda h: sum(r.get("seed_set_sha256") == h for _, r in part))
            i, r = next((i, r) for i, r in part if r.get("seed_set_sha256") != common and not r.get("subset"))
            add("R4", f"rows[{i}]", f"{env_id} / {r['agent']}: its seed set differs from the other rows of the table and it carries no subset label")
        floors = (summary.get("floors") or {}).get(env_id)
        first = f"rows[{part[0][0]}]"
        present = {r["agent"] for _, r in part if r.get("kind") == "scripted"}
        if not floors:
            add("R8", first, f"{env_id}: the control policies of the environment are unknown, so the floors cannot be checked")
        else:
            need = [floors["reference"], floors.get("no_scan")] + list(floors.get("must_fail") or []) + list(floors.get("ablations") or [])
            absent = [n for n in dict.fromkeys(need) if n and n not in present]
            if absent:
                add("R8", first, f"{env_id}: the table lacks the row(s) {', '.join(absent)} (reference, blind policies, ablations)")
            ref = next((r for _, r in part if r["agent"] == floors["reference"]), None)
            if ref is not None and ref.get("regret_median") is None:
                add("R8", first, f"{env_id}: no regret column (the oracle's optimum is not stored for these instances)")
    comps = summary.get("comparisons") or []
    for j, c in enumerate(comps):
        for side in ("a", "b"):
            r = tiers.get((c.get("env_id"), c.get(side)))
            if r is None or r.get("tier") != "published" or (r.get("instances") or 0) < PILOT_BELOW:
                add("R7", f"comparisons[{j}]", f"{c.get('id')}: {c.get(side)} is a pilot row (fewer than {PILOT_BELOW} instances, or records of schema 1)")
        ra, rb = tiers.get((c.get("env_id"), c.get("a"))), tiers.get((c.get("env_id"), c.get("b")))
        if ra and rb and abs((ra.get("infra_error_rate") or 0) - (rb.get("infra_error_rate") or 0)) > MAX_INFRA:
            add("R10", f"comparisons[{j}]", f"{c.get('id')}: the infrastructure-error rates of the two rows differ by more than {100 * MAX_INFRA:.0f} points")
    if published or comps:
        where = f"rows[{published[0][0]}]" if published else "comparisons[0]"
        if not plan or not plan_sha:
            add("R11", where, "published rows without a registered analysis plan (analysis_plan.json)")
        else:
            planned, computed = list(plan.get("comparisons") or []), [c.get("id") for c in comps]
            if sorted(planned) != sorted(computed):
                absent, extra = sorted(set(planned) - set(computed)), sorted(set(computed) - set(planned))
                add("R11", where, "comparisons[] is not the planned family"
                    + (f"; not computed: {', '.join(absent)}" if absent else "") + (f"; not planned: {', '.join(extra)}" if extra else ""))
    return out


def format_violation(path: str, v: dict) -> str:
    return f"{path}:{v['line']}: {v['rule']} ({RULES[v['rule']]}): {v['message']}"
