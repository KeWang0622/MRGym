"""The results table: rebuilt from the saved episode records, never typed by hand.

    mrgym results                    rebuild results/results.json and the table in results/README.md
    mrgym results --dir runs/first   the same for another run folder
    mrgym results --check            write nothing; exit 1 if the stored table or JSON differs from a fresh build, if a
                                     published row breaks a reporting rule (R1-R13, D1), or if a stored conversation is
                                     missing or does not have the hash stored in its record
    mrgym results --check --dir D    D holds results.json and README.md but no episodes/ (an archive: the records
                                     were removed): compares the README table with results.json and applies the
                                     rules to both; says that nothing was compared with records
    mrgym results --check --lint F   apply the reporting rules to the given files only (a results.json, or Markdown
                                     with --context results.json); prints ``file:line: rule: message``
    mrgym results --register-plan --models a,b    write analysis_plan.json before the first episode of a run
    mrgym results --oracle           compute the oracle's optimum of every instance played (the regret column)

A results folder holds ``episodes/<agent>/<env>/L<level>/s<seed>/e<k>/record.json`` (written by ``mrgym run-agent``),
``results.json`` (provenance, one row per environment and agent, the planned comparisons, reliability) and
``README.md``. Optional inputs in the folder: ``analysis_plan.json`` (the plan: design, planned comparisons, stop
rules; registered before the run), ``prices.json`` (model, date, USD per million tokens in / out, source URL; without
it no dollar figure is printed) and ``oracle.json`` (the optimum per instance, written by ``--oracle``).
In the README the generated part stands between two marker lines; text outside the markers is kept as it is, and is
scanned by the text rules.

    <!-- RESULTS:START -->
    ...dateline, published table, comparisons, pilot rows, reliability, design, reading notes...
    <!-- RESULTS:END -->

``table_markdown(dir)`` and ``dateline(dir)`` return the same text for other generated pages.
"""
from __future__ import annotations

import datetime
import json
import os
import re

from . import record as _record
from .agents import summarize
from .stats import lint, power

START, END = "<!-- RESULTS:START -->", "<!-- RESULTS:END -->"
DEFAULT_DIR = "results"
TEMPLATE = """# Results

Generated by `mrgym results --dir {dir}` from the episode records under `episodes/`. Do not edit between the markers.

{start}
{end}
"""


def _summary(directory: str, records=None) -> dict:
    records = summarize.load(directory) if records is None else records
    return summarize.summarise(records, summarize.load_plan(directory), summarize.read_json(directory, summarize.PRICES_FILE),
                               summarize.read_json(directory, summarize.ORACLE_FILE))


def dateline(directory: str = DEFAULT_DIR) -> str:
    """One line: what was run, when, on which engine and package version, and how much of it is published."""
    return summarize.dateline(_summary(directory))


def table_markdown(directory: str = DEFAULT_DIR, agents=None) -> str:
    """The results tables as Markdown. ``agents`` keeps only the named agents (for a short excerpt on another page)."""
    return summarize.markdown(_summary(directory), agents)


def _block(summary: dict) -> str:
    return summarize.dateline(summary) + "\n\n" + summarize.markdown(summary)


def block(directory: str = DEFAULT_DIR) -> str:
    """What stands between the markers of ``<dir>/README.md``."""
    return _block(_summary(directory))


def _with_block(readme: str, text: str) -> str:
    """``readme`` with the part between the markers replaced by ``text``; markers are appended if there are none."""
    if START in readme and END in readme and readme.index(START) < readme.index(END):
        head, rest = readme.split(START, 1)
        return head + START + "\n" + text + END + rest.split(END, 1)[1]
    return readme.rstrip("\n") + ("\n\n" if readme.strip() else "") + START + "\n" + text + END + "\n"


def _read(path: str) -> str | None:
    try:
        with open(path, encoding="utf-8") as f:
            return f.read()
    except OSError:
        return None


def build(directory: str = DEFAULT_DIR, summary: dict | None = None) -> dict[str, str]:
    """Fresh content of the generated files: ``{"results.json": text, "README.md": text}``. Writes nothing."""
    summary = _summary(directory) if summary is None else summary
    readme = _read(os.path.join(directory, "README.md"))
    if readme is None:
        readme = TEMPLATE.format(dir=directory, start=START, end=END)
    readme = _with_block(readme, _block(summary))
    return {"results.json": summarize.json_text(summary), "README.md": fill_stat_spans(readme, summary) if "<!-- STAT:" in readme else readme}


def audit(directory: str = DEFAULT_DIR) -> tuple[list[str], list[str], dict]:
    """Everything ``mrgym results --check`` looks at, from one read of the records: (names of the stored files that
    differ from a fresh build, broken rules as ``file:line: rule: message`` lines, the fresh summary).

    The rules: the reporting rules on the fresh ``results.json``, the text rules on the hand-written part of the
    README, and the stored conversations of the published model rows (present, hash as recorded, every tool message
    answers a call)."""
    records = summarize.load(directory)
    summary = _summary(directory, records)
    fresh = build(directory, summary)
    drift = [name for name, text in fresh.items() if _read(os.path.join(directory, name)) != text]
    out = [lint.format_violation(os.path.join(directory, "results.json"), v) for v in lint.lint_results(summary, fresh["results.json"])]
    out += [lint.format_violation(os.path.join(directory, "README.md"), v) for v in lint.lint_text(fresh["README.md"], summary)]
    published = {(r["env_id"], r["agent"]) for r in summary["rows"] if r["tier"] == "published" and r["kind"] != "scripted"}
    bad = 0
    for r in records:
        if (r["env_id"], r["agent"]) in published and r["status"] == "completed":
            problem = _record.transcript_problem(r, os.path.join(directory, r["_dir"]))
            if problem:
                bad += 1
                if bad <= 20:
                    out.append(f"{os.path.join(directory, r['_dir'], 'record.json')}:1: R13 ({lint.RULES['R13']}): {problem}")
    if bad > 20:
        out.append(f"{directory}: R13 ({lint.RULES['R13']}): {bad - 20} more records without a verifiable conversation")
    return drift, out, summary


def audit_archive(directory: str = DEFAULT_DIR) -> tuple[list[str], list[str], dict] | None:
    """The check of a folder that holds ``results.json`` and no ``episodes/``: an archive, whose records were removed.
    None when there is no ``results.json``. Nothing here is compared with episode records: the stored JSON is taken as
    it is, the README must hold the table that this JSON renders to, and the reporting rules are applied to both."""
    raw = _read(os.path.join(directory, "results.json"))
    if raw is None:
        return None
    summary = json.loads(raw)
    fresh = build(directory, summary)
    drift = [name for name, text in fresh.items() if _read(os.path.join(directory, name)) != text]
    out = [lint.format_violation(os.path.join(directory, "results.json"), v) for v in lint.lint_results(summary, raw)]
    out += [lint.format_violation(os.path.join(directory, "README.md"), v) for v in lint.lint_text(fresh["README.md"], summary)]
    return drift, out, summary


def check(directory: str = DEFAULT_DIR) -> list[str]:
    """Names of the stored files that differ from a fresh build (empty: no drift)."""
    return audit(directory)[0]


def violations(directory: str = DEFAULT_DIR) -> list[str]:
    """Every reason ``mrgym results --check`` fails beyond drift, as ``file:line: rule: message`` lines."""
    return audit(directory)[1]


def lint_files(paths, context: str | None = None) -> list[str]:
    """Apply the reporting rules to files: ``.json`` is read as a results.json, anything else as Markdown, with the
    results of ``context`` (a results.json) as what the text talks about."""
    summary = None
    if context:
        with open(context, encoding="utf-8") as f:
            summary = json.load(f)
    out = []
    for path in paths:
        text = _read(path)
        if text is None:
            out.append(f"{path}:1: cannot be read")
        elif path.endswith(".json"):
            out += [lint.format_violation(path, v) for v in lint.lint_results(json.loads(text), text)]
        else:
            out += [lint.format_violation(path, v) for v in lint.lint_text(text, summary)]
    return out


STAT = re.compile(r"(<!--\s*STAT:([^\s>]+)\s*-->)(.*?)(<!--\s*/STAT\s*-->)", re.S)


def stat_value(summary: dict, key: str) -> str:
    """The text of a ``<!-- STAT:key -->`` span. Keys:

        records | published_records | pilot_records | completed       counts of episode records
        row:<env id>:<agent>                                          the cell ``k/N (rate; 95 % interval)``
        row:<env id>:<agent>:<field>                                  one field of the row (instances, episodes, ...)
        comparison:<id>                                               ``+d.d points (lo to hi), p (Holm) = ...``

    Raises ``KeyError`` with a readable message for a key that does not resolve: a number that is not in
    results.json cannot be printed."""
    parts = key.split(":")
    if parts[0] in ("records", "published_records", "pilot_records", "completed") and len(parts) == 1:
        return str(summary[parts[0]])
    if parts[0] == "row" and len(parts) >= 3:
        field = parts[3] if len(parts) > 3 and parts[-1] not in {r["agent"] for r in summary["rows"]} else None
        agent = ":".join(parts[2:-1] if field else parts[2:])
        row = next((r for r in summary["rows"] if r["env_id"] == parts[1] and r["agent"] == agent), None)
        if row is None or (field and field not in row):
            raise KeyError(f"STAT:{key}: no such row or field in results.json")
        return str(row[field]) if field else summarize.cell_text(row)
    if parts[0] == "comparison":
        c = next((c for c in summary["comparisons"] if c["id"] == key.split(":", 1)[1]), None)
        if c is None:
            raise KeyError(f"STAT:{key}: no such comparison in results.json")
        return f"{100 * c['diff']:+.1f} points ({100 * c['ci95'][0]:+.1f} to {100 * c['ci95'][1]:+.1f}), p (Holm) = {c['p_holm']:.2g}"
    raise KeyError(f"STAT:{key}: unknown key")


def fill_stat_spans(text: str, summary: dict) -> str:
    """``text`` with the content of every STAT span replaced by its value from ``summary``."""
    return STAT.sub(lambda m: m.group(1) + stat_value(summary, m.group(2)) + m.group(4), text)


def write(directory: str = DEFAULT_DIR) -> list[str]:
    """Rebuild the generated files. Returns the paths written."""
    paths = []
    for name, text in build(directory).items():
        path = os.path.join(directory, name)
        with open(path, "w", encoding="utf-8") as f:
            f.write(text)
        paths.append(path)
    return paths


# ------------------------------------------------------------------ the analysis plan
def new_plan(models, env_ids, floor: dict | None = None, suite: str = "report", registered_utc: str | None = None,
             looks: int = 1) -> dict:
    """An analysis plan for a run of ``models`` on ``env_ids`` over the instances of ``suite``: the design, the
    primary endpoint, every pair of models per environment (two-sided) and every model against the strongest floor
    row of the environment (one-sided: model > floor), Holm within an environment. ``floor`` names the floor policy
    per environment; by default the blind policy with the largest upper bound in the stored gate result."""
    from . import manifest
    design = manifest.build(suite, env_ids)
    comparisons, mde = [], {}
    for env_id in env_ids:
        short = env_id.split("/")[-1]
        for i, a in enumerate(models):
            for b in models[i + 1:]:
                comparisons.append(dict(id=f"{short}:{a}-vs-{b}", env_id=env_id, a=a, b=b, alternative="two-sided"))
        fl = (floor or {}).get(env_id) or default_floor(env_id)
        for a in models:
            comparisons.append(dict(id=f"{short}:{a}-vs-{fl}", env_id=env_id, a=a, b=fl, alternative="greater"))
        m = design["environments"][env_id]["instances"]
        family = sum(c["env_id"] == env_id for c in comparisons)
        mde[env_id] = round(100 * power.mde_paired(m, power.PUBLISHED_MIN_EPISODES, comparisons=max(1, family)), 1)
    return dict(
        schema=summarize.PLAN_SCHEMA,
        registered_utc=registered_utc or datetime.datetime.now(datetime.timezone.utc).strftime("%Y-%m-%dT%H:%M:%SZ"),
        design=dict(suite=suite, split=design["split"], episodes=power.PUBLISHED_MIN_EPISODES,
                    instances={e: v["instances"] for e, v in design["environments"].items()},
                    seed_set_sha256={e: v["seed_set_sha256"] for e, v in design["environments"].items()},
                    strata="levels, equal allocation", scripted_episodes=1,
                    sampling="the provider's documented default temperature, sent explicitly and recorded; not tuned"),
        primary_endpoint="pass rate per environment (reward = 1), instance-clustered Wilson interval",
        secondary_endpoints=["mean reward", "regret against the oracle (median, 95th percentile)", "pass^2 (both episodes pass)",
                             "per-level pass rates (descriptive; no comparison is computed from them)"],
        comparisons=comparisons, alpha=0.05, correction="holm", mde_points=mde,
        exclusions="an episode that ended in an endpoint or runner failure (infra_error) is replayed and is not a result; "
                   "every other started episode counts, with reward 0 when nothing was delivered; no instance is dropped",
        stop_rules=dict(
            checkpoint_selection="on a validation suite (at least 200 instances, one episode each, sampling temperature), "
                                 "never on the reporting instances",
            looks=looks, look_level=0.05 / looks,
            efficacy="one-sided paired test of checkpoint against base at alpha / looks (mrgym.stats.sequential.checkpoint_look)",
            futility="stop when the one-sided upper bound of the paired difference at 1 - alpha / looks is below mde_points",
            within_evaluation="mrgym.stats.betting_test on the instances in manifest order; stop when the wealth reaches 1 / alpha"))


def default_floor(env_id: str) -> str:
    """The floor row a model is compared with: the blind policy with the largest upper bound in the stored gate result
    of the environment; without a stored gate, the constant recipe if the family has one, else its first blind policy."""
    import mrgym

    from . import gate, policies
    stored = gate.load(env_id)
    if stored:
        names = [lv["blind_ceiling"]["policy"].split("#")[0] for lv in stored["levels"].values() if lv.get("blind_ceiling")]
        if names:
            return max(sorted(set(names)), key=names.count)
    controls = policies.controls_of(mrgym.spec(env_id))
    must_fail = list(getattr(controls, "MUST_FAIL", ()))
    return "fixed_recipe" if "fixed_recipe" in must_fail or not must_fail else must_fail[0]


def write_oracle(directory: str = DEFAULT_DIR) -> str:
    """Compute the oracle's optimum of every instance the records of ``directory`` played, for the environments that
    ship an oracle, and write ``oracle.json``. One process; about the time of 100 noise-free scans per instance.
    Instances already stored are kept (the optimum of an instance does not change on one engine)."""
    import mrgym

    from .envs import oracle as O
    stored = summarize.read_json(directory, summarize.ORACLE_FILE) or {}
    records = summarize.load(directory)
    for env_id in sorted({r["env_id"] for r in records}):
        try:
            module = O.load(env_id)
        except mrgym.Error:
            module = None
        if module is None:
            continue
        entry = stored.get(env_id) if (stored.get(env_id) or {}).get("engine") == mrgym.ENGINE_ID else None
        entry = entry or dict(kind=module.REGRET_KIND, engine=mrgym.ENGINE_ID, instances={})
        for level, split, seed in sorted({(r["level"], r.get("split") or "train", r["seed"]) for r in records if r["env_id"] == env_id}, key=str):
            key = f"L{level}:{seed}"
            if key not in entry["instances"]:
                env = mrgym.make(env_id, level=level, seed=seed, split=split)
                env.reset()
                entry["instances"][key] = module.solve(env.episode_config(), env.hidden_world())["value"]
                env.close()
        stored[env_id] = entry
    path = os.path.join(directory, summarize.ORACLE_FILE)
    with open(path, "w", encoding="utf-8") as f:
        json.dump(stored, f, indent=1, sort_keys=True)
        f.write("\n")
    return path


# ------------------------------------------------------------------ command line
def cmd_results(a) -> int:
    if a.lint:
        found = lint_files(a.lint, a.context)
        for line in found:
            print(line)
        if not found:
            print(f"{len(a.lint)} file(s): no reporting rule is broken")
        return 1 if found else 0
    if a.register_plan:
        import mrgym
        path = os.path.join(a.dir, summarize.PLAN_FILE)
        if os.path.exists(path) and os.path.isdir(os.path.join(a.dir, "episodes")) and any(r["record_schema"] == 2 for r in summarize.load(a.dir)):
            print(f"mrgym results: {path} exists and the folder holds records of schema 2; a plan is registered before the run, once")
            return 1
        models = [m for part in a.models or [] for m in part.split(",") if m]
        envs = [e for part in a.env or [] for e in part.split(",") if e] or \
            [i for i in mrgym.list_envs() if mrgym.spec(i).family and mrgym.spec(i).kind in ("admitted", "candidate")]
        os.makedirs(a.dir, exist_ok=True)
        with open(path, "w", encoding="utf-8") as f:
            json.dump(new_plan(models, envs, suite=a.suite), f, indent=1)
            f.write("\n")
        print("written:", path)
        return 0
    archive = audit_archive(a.dir) if a.check and not os.path.isdir(os.path.join(a.dir, "episodes")) else None
    if archive:
        drift, broken, s = archive
        for name in drift:
            print(f"drift: {os.path.join(a.dir, name)} is not what the stored results.json renders to")
        for line in broken:
            print(line)
        if not drift and not broken:
            print(f"{a.dir}: an archive without episode records, so nothing was compared with records. README.md holds the table "
                  f"of results.json ({s['records']} records when it was built: {s['published_records']} published, "
                  f"{s['pilot_records']} pilot); no reporting rule is broken")
        return 1 if drift or broken else 0
    if not os.path.isdir(os.path.join(a.dir, "episodes")):
        print(f"mrgym results: no episode records under {os.path.join(a.dir, 'episodes')}; run mrgym run-agent --out {a.dir} first")
        return 1
    if a.oracle:
        print("written:", write_oracle(a.dir))
        return 0
    if a.check:
        drift, broken, s = audit(a.dir)
        for name in drift:
            print(f"drift: {os.path.join(a.dir, name)} differs from a fresh build; run mrgym results --dir {a.dir}")
        for line in broken:
            print(line)
        if not drift and not broken:
            print(f"{a.dir}: results.json and the table in README.md match the {s['records']} episode records "
                  f"({s['published_records']} published, {s['pilot_records']} pilot); no reporting rule is broken")
        return 1 if drift or broken else 0
    for path in write(a.dir):
        print("written:", path)
    if not a.quiet:
        print()
        print(block(a.dir), end="")
    return 0


def add_parser(sub) -> None:
    """Register ``mrgym results``."""
    p = sub.add_parser("results", help="rebuild (or check) the results table from the saved episode records")
    p.add_argument("--dir", default=DEFAULT_DIR, help="results folder with episodes/ (default results)")
    p.add_argument("--check", action="store_true", help="write nothing; exit 1 on drift or a broken reporting rule")
    p.add_argument("--lint", nargs="+", metavar="FILE", help="with --check: apply the reporting rules to these files only")
    p.add_argument("--context", metavar="RESULTS_JSON", help="with --lint: the results.json the Markdown files talk about")
    p.add_argument("--register-plan", action="store_true", help="write analysis_plan.json (before the first episode of a run)")
    p.add_argument("--models", action="append", metavar="NAMES", help="with --register-plan: the models of the run, comma list")
    p.add_argument("--env", action="append", metavar="IDS", help="with --register-plan: environments (default: admitted and candidate ids)")
    p.add_argument("--suite", default="report", help="with --register-plan: the suite of reporting instances (default report)")
    p.add_argument("--oracle", action="store_true", help="compute and store the oracle's optimum of every instance played")
    p.add_argument("--quiet", action="store_true", help="do not print the table")
    p.set_defaults(fn=cmd_results)
