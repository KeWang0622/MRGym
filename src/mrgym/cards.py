"""Environment cards: one dict per environment id, rendered to Markdown, linted for completeness.

A card answers, in this order, what a user of an environment asks: what is on the table, what is hidden, what the
agent can do and what it costs, what it must deliver, how the reward is computed, which shortcut policies were tried
and what they scored. The authored part lives next to the environment (``card()``); status and control-policy
results are loaded from the stored admission run and never typed by hand.
"""
from __future__ import annotations

REQUIRED = ("id", "title", "kind", "status", "given", "deliver", "scored_by", "summary", "world", "hidden", "told", "levels",
            "limits", "deliverable", "reward", "controls", "measured", "determinism")


def slug(env_id: str) -> str:
    """Folder name of an environment card: ``Scanner/NoWrap-v0`` -> ``scanner-nowrap-v0``."""
    return env_id.replace("/", "-").lower()


def lint(card: dict) -> list[str]:
    """Problems that keep a card from being published."""
    bad = [f"missing field: {k}" for k in REQUIRED if k not in card]
    if bad:
        return bad
    if card["kind"] == "sandbox":
        return bad
    if not any(c["must"] == "pass" for c in card["controls"]):
        bad.append("no reference policy (a control that must pass)")
    if sum(c["must"] == "fail" for c in card["controls"]) < 3:
        bad.append("fewer than three shortcut controls that must fail")
    if card["measured"] is None:
        bad.append("no measured control results (run `mrgym check <id> --admission --write`)")
    else:
        for lv, m in card["measured"]["levels"].items():
            for c in card["controls"]:
                if c["name"] not in m["controls"]:
                    bad.append(f"control {c['name']} has no measured result at level {lv}")
    return bad


def _pct(k, n):
    return f"{k}/{n} ({100 * k / n:.0f}%)" if n else "-"


def controls_table(card: dict) -> list[str]:
    m = card["measured"]
    if not m:
        return ["Control policies have not been run for this id."]
    lvs = sorted(m["levels"])
    out = [f"Run {m['date_utc']} on engine `{m['engine']}`, package {m['package_version']}: `{m['command']}` "
           f"({m['seeds']}). Per policy and level: instances on which the policy passed at least once, and the mean reward.", "",
           "| Policy | Must | " + " | ".join(f"L{lv} passed | L{lv} reward" for lv in lvs) + " | What it does |",
           "|---|---|" + "---:|---:|" * len(lvs) + "---|"]
    for c in card["controls"]:
        cells = []
        for lv in lvs:
            r = m["levels"][lv]["controls"].get(c["name"])
            cells += [_pct(r["instances_passed_at_least_once"], m["levels"][lv]["instances"]), f"{r['reward_mean']:.2f}"] if r else ["-", "-"]
        out.append(f"| `{c['name']}` | {c['must']} | " + " | ".join(cells) + f" | {c['what']} |")
    out += ["", "Admitted instances (reference passes, every must-fail policy fails): "
            + ", ".join(f"L{lv} {_pct(m['levels'][lv]['admitted'], m['levels'][lv]['instances'])}" for lv in lvs) + "."]
    reasons = {lv: m["levels"][lv]["rejection_reasons"] for lv in lvs if m["levels"][lv]["rejection_reasons"]}
    if reasons:
        out.append("Rejection reasons (instances): " + "; ".join(
            f"L{lv}: " + ", ".join(f"{k} {v}" for k, v in r.items()) for lv, r in reasons.items()) + ".")
    return out


def markdown(card: dict, tools: list | None = None, statement: str | None = None) -> str:
    w, r = card["world"], card["reward"]
    lv0 = card.get("default_level", sorted(card["levels"])[0])
    out = [f"<!-- Generated by tools/generate.py from the registry; edit the card() next to the environment. -->",
           f"# `{card['id']}` · {card['title']}", "", f"**Status:** {card['status']}", "", card["summary"], ""]
    if card.get("why_practice"):
        out += [card["why_practice"], ""]
    out += ["```python", "import mrgym", f"env = mrgym.make(\"{card['id']}\", level={lv0}, seed=0)", "obs, info = env.reset()",
            "obs, reward, terminated, truncated, info = env.step({\"name\": \"scanner_info\", \"arguments\": {}})", "```", "",
            "| Given | Deliver | Scored by |", "|---|---|---|", f"| {card['given']} | {card['deliver']} | {card['scored_by']} |", "",
            "## World", "", f"- On the table: {w['phantom']}", f"- Sequences that matter here: {', '.join(w['sequences_useful'])}",
            f"- Formulas the agent is given: {w['agent_side_formulas']}", "",
            "| Hidden (measurable only by scanning) | Told |", "|---|---|"]
    for i in range(max(len(card["hidden"]), len(card["told"]))):
        out.append(f"| {card['hidden'][i] if i < len(card['hidden']) else ''} | {card['told'][i] if i < len(card['told']) else ''} |")
    if tools:
        out += ["", "## Tools", "", "| Tool | Cost | Counts as scanner request | Ends episode |", "|---|---|---|---|"]
        out += [f"| `{t['name']}` | {t['cost'].replace('_', ' ')} | {'yes' if t['counted'] else 'no'} | {'yes' if t['terminal'] else 'no'} |" for t in tools]
        out += ["", f"Limits: {card['limits']['max_scanner_requests']} scanner requests and {card['limits']['max_tool_calls']} tool calls per episode."]
    out += ["", "## Levels", "", "| Level | Hidden-world prior | Budget (s) |", "|---|---|---|"]
    out += [f"| {lv} | {d['summary']} | {d['budget_s'][0]:g}" + (f" to {d['budget_s'][1]:g}" if d["budget_s"][1] != d["budget_s"][0] else "") + " |"
            for lv, d in sorted(card["levels"].items())]
    out += ["", "## Deliverable and reward", "", f"- Deliverable: `{card['deliverable']['tool']}` with `{card['deliverable']['format']}`",
            f"- Reward range {r['range']}; paid {r['when']}"]
    if r["gates"]:
        out += ["- Gates: " + "; ".join(r["gates"]), f"- Error: `{r['error']}`", f"- Score: `{r['score']}`", f"- Passing: {r['passing']}"]
    if card["kind"] != "sandbox":
        out += ["", "## Control policies", ""] + controls_table(card)
    if statement:
        out += ["", "## What the agent reads at reset (level %s, seed 0)" % lv0, "", "~~~text", statement.rstrip(), "~~~"]
    out += ["", "## Determinism and versions", "", card["determinism"] + ".", "",
            "Rewards are comparable only within one environment version (the `-vN` suffix) and one scanner engine "
            "(`mrgym --version`)."]
    return "\n".join(out) + "\n"
