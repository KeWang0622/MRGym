def render_dataset(env_id: str) -> dict:
    """{relative path: text} of the files at the top of one dataset folder."""
    import mrgym
    spec, card = mrgym.spec(env_id), mrgym.card(env_id)
    name = dataset_name(spec)
    return {"README.md": "\n".join([
        f"<!-- {CANARY_LINE} -->", f"<!-- {GENERATED} -->", f"# `{name}`", "",
        f"Harbor tasks for `{spec.id}` ({spec.kind}): {card.get('title', '')}. Each directory under `tasks/` is one seeded instance.", "",
        "Each task has three containers: the agent (`main`, user `agent`), a scanner sidecar (`mrgym serve`) that holds the hidden world "
        "and keeps the keyed log and its head, and a separate verifier without network that replays the log against that head and "
        "scores `/app/answer.json`.", "",
        "```sh", f"python -m mrgym.compat.harbor lint datasets/{name}/tasks/*          # static checks, no Docker",
        f"python -m mrgym.compat.harbor local datasets/{name}/tasks/*         # sidecar + reference policy + verifier in one process: reward 1",
        f"python -m mrgym.compat.harbor local --policy nop datasets/{name}/tasks/*   # no call, no deliverable: reward 0",
        f"harbor lint --extend-select ALL datasets/{name}/tasks/*             # needs the Docker CLI with the Compose plugin",
        f"harbor run -p datasets/{name}/tasks -a oracle                       # needs a Docker daemon and a released mrgym on PyPI",
        "```", "",
        "More instances: `mrgym export harbor --id " + spec.id + " --n <count>`. The hidden seeds are fresh entropy, so two exports "
        "never produce the same task. An explicit `dataset.toml` with task digests is written by `harbor dataset init` and "
        "`harbor dataset add` when the dataset is published.", ""])}


def _write(root: str, files: dict) -> None:
    for rel, text in files.items():
        path = os.path.join(root, rel)
        os.makedirs(os.path.dirname(path), exist_ok=True)
        with open(path, "w", encoding="utf-8", newline="\n") as f:
            f.write(text)
        if rel.endswith(".sh"):
            os.chmod(path, 0o755)


def _stale(root: str, files: dict) -> list[str]:
    bad = []
    for rel, text in files.items():
        path = os.path.join(root, rel)
        try:
            with open(path, encoding="utf-8") as f:
                if f.read() != text:
                    bad.append(f"{path}: differs from the generated text")
        except FileNotFoundError:
            bad.append(f"{path}: missing")
    return bad


def harbor_tasks(out: str) -> list[str]:
    """Task directories under ``out`` (``<out>/mrgym-*/tasks/*`` that hold a task.toml)."""
    found = []
    if os.path.isdir(out):
        for ds in sorted(os.listdir(out)):
            tasks = os.path.join(out, ds, "tasks")
            if ds.startswith("mrgym-") and os.path.isdir(tasks):
                found += [os.path.join(tasks, t) for t in sorted(os.listdir(tasks)) if os.path.exists(os.path.join(tasks, t, "task.toml"))]
    return found


def export_harbor(out: str, ids=None, levels=None, n: int = 1, from_secret: bool = False, base_image: str = BASE_IMAGE) -> list[str]:
    """Write ``n`` new tasks per (scored id, level). Default levels: the id's default level. Returns the task dirs."""
    import mrgym
    written = []
    for env_id in ids or [i for i in mrgym.list_envs() if mrgym.spec(i).kind != "sandbox"]:
        spec = mrgym.spec(env_id)
        for level in levels or [spec.default_level]:
            for k in range(n):
                ep, token = new_episode(env_id, level, f"harbor:{k}" if from_secret else None), new_token()
                root = os.path.join(out, dataset_name(spec), "tasks", task_dirname(ep, token))
                _write(root, render_task(ep, token, base_image))
                written.append(root)
        _write(os.path.join(out, dataset_name(spec)), render_dataset(env_id))
    return written


def refresh_harbor(out: str, base_image: str = BASE_IMAGE) -> list[str]:
    """Render every exported task under ``out`` again, in place, from the seed and the token stored in it. This is what
    to run after the task text, the tools, the card or the package version changed: the instances stay the same.
    Returns the task dirs that were rewritten; a task of an id that is no longer registered is left alone."""
    import mrgym
    done = []
    for root in harbor_tasks(out):
        try:
            ep = harbor.load_episode(os.path.join(root, "tests", "episode.json"))
            with open(os.path.join(root, "environment", "scanner", "agent_token"), encoding="ascii") as f:
                token = f.read().strip()
        except (OSError, ValueError, SystemExit):
            continue
        if ep["env_id"] not in mrgym.registry or os.path.basename(root) != task_dirname(ep, token):
            continue
        _write(root, render_task(ep, token, base_image))
        _write(os.path.dirname(os.path.dirname(root)), render_dataset(ep["env_id"]))
        done.append(root)
    return done


def check_harbor(out: str, base_image: str = BASE_IMAGE) -> list[str]:
    """Problems of the exported tasks under ``out``: stale or hand-edited files, and tasks of ids that are no longer
    registered. Empty = current."""
    import mrgym
    bad = []
    tasks = harbor_tasks(out)
    if not tasks:
        return [f"{out}: no exported task found"]
    for root in tasks:
        try:
            ep = harbor.load_episode(os.path.join(root, "tests", "episode.json"))
        except (OSError, ValueError, SystemExit) as e:
            bad.append(f"{root}: {e}")
            continue
        if ep["env_id"] not in mrgym.registry:
            bad.append(f"{root}: {ep['env_id']} is not registered in this package; delete the task and export again")
            continue
        try:
            with open(os.path.join(root, "tests", "export.json"), encoding="utf-8") as f:
                made = json.load(f)
        except (OSError, ValueError):
            made = {}
        if made.get("engine") != mrgym.ENGINE_ID:                         # another engine: the same seed is another world
            bad.append(f"{root}: exported on {made.get('engine')}, this is {mrgym.ENGINE_ID}; delete the task and export again")
            continue
        try:
            with open(os.path.join(root, "environment", "scanner", "agent_token"), encoding="ascii") as f:
                token = f.read().strip()
        except OSError:
            bad.append(f"{root}: no agent token")
            continue
        if os.path.basename(root) != task_dirname(ep, token):
            bad.append(f"{root}: the directory name does not belong to this task")
        bad += _stale(root, render_task(ep, token, base_image))
        bad += [b for b in _stale(os.path.dirname(os.path.dirname(root)), render_dataset(ep["env_id"])) if b not in bad]
    if any("differs from the generated text" in b or ": missing" in b for b in bad):
        bad.append("the task text, the tools, a card or the version changed since these tasks were rendered: "
                   "`mrgym export harbor --refresh` renders them again from their stored seeds (the instances stay the same)")
    return bad


