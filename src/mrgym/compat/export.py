def render_openenv(env_id: str, level: int | None = None, seed: int = 7) -> dict:
    """The generated files of the OpenEnv package for one id: the manifest (declared tools) and the replay plan (the
    scripted reference policy's calls on a public training seed)."""
    import mrgym
    spec = mrgym.spec(env_id)
    level = spec.default_level if level is None else level
    ep = scripted_episode(env_id, level, seed)
    tools = [t["function"]["name"] for t in ep["tools"]]
    actions = [{"type": "call_tool", "tool_name": c["name"], "arguments": c.get("arguments", {})} for c in ep["calls"]
               if isinstance(c, dict) and isinstance(c.get("name"), str)]
    lo, hi = spec.reward_range
    manifest = "\n".join([
        f"# {GENERATED}", "spec_version: 1", "name: mrgym_scanner_env", f"version: {mrgym.__version__}", "type: space", "runtime: fastapi",
        "app: server.app:app", "port: 8000", "validation:", "  execution:", "    kind: openenv_ws", "    probe_path: validation/runtime.json",
        "    dockerfile: server/Dockerfile", "    context: .", "  reward:", f"    range: [{float(lo)}, {float(hi)}]", "    oracle_tolerance: 0.0",
        "    floor_margin: 0.5", "  resources:", "    cpu: 1.0", "    memory_mb: 2048", "    disk_mb: 2048", "    episode_timeout_s: 600.0",
        "  network:", "    mode: no-network", "  task_distribution:", "    generator_seed: 0", f"    dataset_version: \"{mrgym.ENGINE_ID}\"",
        "  capabilities:", "    verifier:", "      kind: reward_channel", f"    declared_tools: [{', '.join(tools)}]", "  types:",
        "    tags: [science, mri, tool-use]", ""])
    plan = dict(plan_schema_version="1", reset=dict(episode_id="mrgym-smoke", seed=seed, options=dict(env_id=env_id, level=level)), actions=actions)
    default = dict(env_id=env_id, level=level, mrgym=mrgym.__version__, engine=mrgym.ENGINE_ID, reference_reward=ep["reward"], policy=ep["policy"])
    pin = f"mrgym=={mrgym.__version__}"
    pyproject = "\n".join([
        f"# {GENERATED}", "[build-system]", 'requires = ["setuptools>=45", "wheel"]', 'build-backend = "setuptools.build_meta"', "",
        "[project]", 'name = "openenv-mrgym_scanner_env"', f'version = "{mrgym.__version__}"',
        'description = "MR Gym (a virtual MRI scanner operated through priced tool calls) as an OpenEnv environment"',
        'requires-python = ">=3.10"', f'dependencies = ["openenv>=0.14.0", "uvicorn>=0.24.0", "{pin}"]', "",
        "[project.scripts]", 'server = "mrgym_scanner_env.server.app:main"', "",
        "[tool.setuptools]", "include-package-data = true", 'packages = ["mrgym_scanner_env", "mrgym_scanner_env.server"]',
        'package-dir = { "mrgym_scanner_env" = ".", "mrgym_scanner_env.server" = "server" }', "",
        "[tool.setuptools.package-data]", 'mrgym_scanner_env = ["openenv.yaml", "default_env.json", "validation/*.json"]', ""])
    dockerfile = "\n".join([
        f"# {GENERATED}", "# Build context: this package directory.  docker build -f server/Dockerfile -t mrgym_scanner_env .",
        "# Not built where this file was generated unless the report in integrations/README.md says so.",
        f"FROM {BASE_IMAGE}", "WORKDIR /app/env", "COPY . /app/env",
        "RUN pip install --no-cache-dir -r /app/env/server/requirements.txt && useradd -m openenv", "USER openenv", "EXPOSE 8000",
        "HEALTHCHECK --interval=5s --timeout=3s --retries=20 CMD python -c \"import urllib.request; "
        "urllib.request.urlopen('http://127.0.0.1:8000/health')\"",
        'CMD ["uvicorn", "server.app:app", "--host", "0.0.0.0", "--port", "8000"]', ""])
    return {"openenv.yaml": manifest, "validation/runtime.json": json.dumps(plan, indent=1) + "\n",
            "default_env.json": json.dumps(default, indent=1) + "\n", "pyproject.toml": pyproject,
            "server/requirements.txt": f"openenv>=0.14.0\nuvicorn>=0.24.0\n{pin}\n", "server/Dockerfile": dockerfile}


def _openenv_default(out: str):
    try:
        with open(os.path.join(out, "default_env.json"), encoding="utf-8") as f:
            return json.load(f)
    except (OSError, ValueError):
        return None


def export_openenv(out: str, env_id: str | None = None, level: int | None = None) -> str:
    import mrgym
    current = _openenv_default(out) or {}
    scored = [i for i in mrgym.list_envs() if mrgym.spec(i).kind != "sandbox"]
    env_id = env_id or (current.get("env_id") if current.get("env_id") in mrgym.registry else None) or (scored or mrgym.list_envs())[0]
    _write(out, render_openenv(env_id, level))
    return env_id


def check_openenv(out: str) -> list[str]:
    import mrgym
    current = _openenv_default(out)
    if not current:
        return [f"{out}: no default_env.json; run `mrgym export openenv`"]
    if current.get("env_id") not in mrgym.registry:
        return [f"{out}: {current.get('env_id')} is not registered in this package; run `mrgym export openenv --id <id>`"]
    return _stale(out, render_openenv(current["env_id"], current.get("level")))


