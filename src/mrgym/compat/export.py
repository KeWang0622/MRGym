def family_slug(spec) -> str:
    return spec.name.lower()


def dataset_name(spec) -> str:
    return f"mrgym-{family_slug(spec)}-v{spec.version}"


def _toml_str(s: str) -> str:
    return json.dumps(str(s), ensure_ascii=False)


# ------------------------------------------------------------------------------------------------ Harbor
def new_episode(env_id: str, level: int, from_secret: str | None = None) -> dict:
    """A hidden episode file for a new task, in the form ``mrgym serve --episode-file`` reads: ``{"env_id", "level",
    "split", "seed"}`` with a raw 128-bit seed. ``from_secret``: an index; the seed is then the world seed the secret
    (MRGYM_SECRET_FILE) gives that index on the task's split, so the holder of the secret can rebuild the dataset.
    Otherwise fresh entropy."""
    from mrgym import keys
    seed = keys.world_seed(env_id, level, harbor.SPLIT, from_secret) if from_secret is not None else os.urandom(16).hex()
    return dict(env_id=env_id, level=int(level), split=harbor.SPLIT, seed=seed)


def new_token() -> str:
    """A bearer token for the task's episode: the agent's own credential (the agent image holds it). Random, never a
    function of the seed: nothing that leaves the trusted side may let a guessed seed be confirmed."""
    import secrets
    return secrets.token_hex(20)


def task_dirname(ep: dict, token: str) -> str:
    import mrgym
    tag = hashlib.sha256(("harbor-task:" + token).encode()).hexdigest()[:6]           # from the token, not from the seed
    return f"{family_slug(mrgym.spec(ep['env_id']))}-l{ep['level']}-{tag}"


def _card_sections(card: dict, level: int) -> str:
    lv = (card.get("levels") or {}).get(level) or (card.get("levels") or {}).get(str(level)) or {}
    reward = card.get("reward") or {}
    controls = card.get("controls") or []
    ref = [c for c in controls if c.get("must") == "pass"]
    fail = [c for c in controls if c.get("must") == "fail"]
    out = ["## Difficulty", ""]
    out.append(f"Level {level}: {lv.get('summary', 'no level description on the card')}.")
    hidden = card.get("hidden") or []
    if hidden:
        out.append("Hidden from the agent and measurable only by scanning: " + "; ".join(hidden) + ".")
    out.append("No expert time estimate has been recorded for this family.")
    out += ["", "## Reference solution", ""]
    if ref:
        out += [f"`solution/solve.sh` plays the scripted policy `{c['name']}` against the scanner service: {c.get('what', '')}" for c in ref]
    else:
        out.append("This id has no scripted reference policy.")
    out += ["", "## Verification", "",
            "`tests/test.sh` runs in a separate container without network. Harbor copies the scanner sidecar's log directory and state "
            "directory into it. The verifier rebuilds the hidden world from the seed, replays the keyed log against the head receipt the "
            "sidecar kept in its state directory (a log that is shortened, edited, foreign or not sealed fails), and scores "
            "`/app/answer.json` with the code that scores in process. The reward is the environment's: 1 for a pass, 0 otherwise."]
    if reward.get("gates"):
        out.append("Gates: " + "; ".join(reward["gates"]) + ".")
    if reward.get("error"):
        out.append(f"Error measure: {reward['error']}.")
    if reward.get("passing"):
        out.append(f"Passing: {reward['passing']}.")
    if fail:
        out.append("Scripted shortcut policies that must fail: " + ", ".join(f"`{c['name']}`" for c in fail) + ".")
    return "\n".join(out)


