"""``mrgym export harbor | openenv``: the generated forms of the registry for other frameworks.

    mrgym export harbor  [--out datasets] [--id ID ...] [--level N] [--n 1] [--from-secret] [--check | --refresh]
        datasets/mrgym-<family>-v<N>/tasks/<family>-l<level>-<6 hex>/     one Harbor task per instance:
            scanner sidecar (``mrgym serve``, holds the hidden world) + agent container + separate verifier
            (see mrgym.compat.harbor)
    mrgym export openenv [--out integrations/openenv/mrgym_scanner_env] [--id ID] [--check]
        the generated files of the OpenEnv package: openenv.yaml (declared tools of the id), validation/runtime.json
        (the reference policy's calls as a replay plan), the pins

Everything is rendered from the registry (``mrgym.list_envs``, ``env.tools``, the environment card), so a new family
is exported with no change here. ``--check`` renders again and fails when a file on disk differs: a generated file
that was edited by hand, or one that is stale after a change of the tools, the card or the package version.

Every run of ``mrgym export harbor`` adds new instances (new seeds). ``--refresh`` renders the existing tasks again from
their stored seeds; ``--check`` and ``--refresh`` are deterministic: the text of a task is a function of its stored seed,
its stored token and the registry.

A Harbor task holds a hidden episode file with a raw 128-bit seed. It is drawn from the operating system (or, with
``--from-secret``, derived from the secret in MRGYM_SECRET_FILE), never from a public integer: a policy that
enumerates public seeds cannot rebuild the world. ``--check`` re-renders every task from the seed already stored in it.
(The command line is registered in ``mrgym.cli`` together with the episode export of ``mrgym.export``.)
"""
