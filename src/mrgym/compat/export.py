def cmd_export(a) -> int:
    if a.target == "harbor":
        out = a.out or "datasets"
        if a.check:
            bad = check_harbor(out)
            print("\n".join(bad) if bad else f"{len(harbor_tasks(out))} Harbor task(s) under {out} are current")
            return 1 if bad else 0
        if getattr(a, "refresh", False):
            for root in refresh_harbor(out):
                print("rendered again:", root)
            return 0
        for root in export_harbor(out, a.id, [a.level] if a.level else None, a.n, a.from_secret):
            print("written:", root)
        return 0
    out = a.out or os.path.join("integrations", "openenv", "mrgym_scanner_env")
    if a.check:
        bad = check_openenv(out)
        print("\n".join(bad) if bad else f"the OpenEnv package under {out} is current")
        return 1 if bad else 0
    if a.id and len(a.id) > 1:
        print("mrgym export openenv takes one --id", file=sys.stderr)
        return 2
    print(f"written: {out} for {export_openenv(out, a.id[0] if a.id else None, a.level)}")
    return 0
