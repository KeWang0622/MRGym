"""``docs/physics/measured.md`` from the stored table (``docs/physics/measured/results.json``).

A pure function of the stored table: no engine, no numpy. ``tools/generate.py`` writes and checks the page with it,
``tools/measured/run_all.py --write`` writes the table and the page together.
"""

HEAD = "<!-- Generated by tools/generate.py from docs/physics/measured/results.json; that table is written by `python tools/measured/run_all.py --write`. -->"


def verdict(q) -> str:
    if q["declared"]:
        return "declared difference" if q["passed"] else "**declared difference, GROWN**"
    return "pass" if q["passed"] else "**FAIL**"


def markdown(t: dict) -> str:
    s = t["sessions"]
    rows = [q for r in t["rungs"] for q in r["rows"]]
    tested, declared = [q for q in rows if not q["declared"]], [q for q in rows if q["declared"]]
    failed = [q["id"] for q in tested if not q["passed"]]
    grown = [q["id"] for q in declared if not q["passed"]]
    out = [HEAD, "# Comparison with measured data", "",
           f"Engine `{t['engine']}`. **What is shown:** statistics of images and signals from public phantom sessions on real scanners ({s['m6']} scanners with the "
           f"ACR phantom, {s['m1']} T1 maps of the NIST plate from the ISMRM 2020 challenge, {s['m8']} acquisitions of a fat-water phantom, {s['m7']} session with a gel "
           f"sphere, {s['m9']} session with the NIST T2 plate as raw data, and published phantom measurements), each next to the engine's own model of the same protocol, "
           "analysed with the same estimator. **What is not shown:** a scan of this console's sequences on one physical object. No image of the six console "
           "sequences has been compared pixel by pixel with a scan of the same object (rung M14); the rows compare region signals, fitted values and image statistics.", "",
           "Every row gives the measurement with its spread and n, the engine, the difference, and either a tolerance taken from the spread of the measurement or the words "
           "\"declared difference\": a number the engine is known to get wrong, listed with what would close it under "
           "[Known differences from measurement](#known-differences-from-measurement). A row that fails is listed, not hidden.", "",
           f"**State of this table:** {len(tested) - len(failed)} of {len(tested)} rows with a tolerance pass"
           + (f" (failed: {', '.join(failed)})" if failed else "") + f"; {len(declared)} declared differences"
           + (f", of which {', '.join(grown)} grew past the size at which they were declared" if grown else ", none larger than when it was declared") + ".", "",
           "Regenerate: `python tools/measured/run_all.py --write`. Check: `python tools/measured/run_all.py --check`. Rebuild the cached extracts from the public "
           "originals (about 0.7 GB of downloads into a folder outside the repository): `python tools/measured/run_all.py --fetch --cache DIR --write`.", "",
           "| Rung | What is compared | Measured data | Rows with a tolerance | Declared differences |", "|---|---|---|---|---|"]
    for r in t["rungs"]:
        a, b = [q for q in r["rows"] if not q["declared"]], [q for q in r["rows"] if q["declared"]]
        out.append(f"| [{r['rung']}](#{anchor(r)}) | {r['title']} | {r['source']} | "
                   + (f"{sum(q['passed'] for q in a)} of {len(a)} pass" if a else ("not run" if not r["rows"] else "-")) + f" | {len(b) or '-'} |")
    out.append("")
    for r in t["rungs"]:
        out += [f"## {r['rung']}. {r['title']}", "", f"Measured data: {r['source']}." + (f" Engine `{r['engine']}`, {r['date_utc']}." if r.get("engine") else ""), ""]
        if r["rows"]:
            out += ["| # | Quantity | Measured (spread, n) | Engine | Difference | Tolerance | |", "|---|---|---|---|---|---|---|"]
            out += [f"| {q['id']} | {q['quantity']} | {q['measured']} | {q['engine']} | {q['difference']} | {'-' if q['declared'] else q['tolerance']} | {verdict(q)} |" for q in r["rows"]]
            out.append("")
        out += [f"{q['id']}: {q['note']}" for q in r["rows"] if q["note"]]
        out += ([""] if any(q["note"] for q in r["rows"]) else []) + [f"- {n}" for n in r["notes"]] + [""]
    out += ["## Rungs not run", "", "| Rung | What it would be | State |", "|---|---|---|"]
    out += [f"| {x['rung']} | {x['what']} | {x['state']} |" for x in t["not_run"]]
    out += ["", "## Known differences from measurement", "",
            "What the engine gets wrong or cannot say on these rungs. The number of each line is read from the rows named in brackets. Lines 1 to 12 were found "
            "by the first comparison; 13 and 14 by rung M9. Two rows are differences of the measured object or of a published value, not of the engine, and are "
            "not in this list: M9.3 (two spheres of the measured phantom do not hold the published solution) and M5.2 (T1 of blood).", "",
            "| # | What | Number | What would close it |", "|---:|---|---|---|"]
    out += [f"| {k['n']} | {k['what']} | {'; '.join(k['numbers']) or 'no number (rows ' + ', '.join(k['rows']) + ' not run)'} | {k['closes']} |" for k in t["known"]]
    out += ["", "## The cached extracts", "",
            "Each rung reads a small extract under `docs/physics/measured/`. An original is stored only where its licence allows it; where there is none, only numbers "
            "derived from it are kept and the original is fetched by `--fetch`; where the licence is unclear, nothing is kept. Every file carries `source`, `url`, `licence`, "
            "`citation`, `retrieved` and the `sha256` of the original.", "",
            "| File | Source | Licence | What is stored | sha256 of the original |", "|---|---|---|---|---|"]
    for x in t["sources"]:
        sha = x["sha256"]
        sha = "-" if not sha else (f"`{sha[:16]}…`" if isinstance(sha, str) else "; ".join(f"`{v[:16]}…` ({k})" for k, v in sha.items()))
        out.append(f"| {('`' + x['file'] + '`') if x['file'] else 'none'} | {x['source']} (retrieved {x['retrieved']}) | {x['licence']} | {x['stored']} | {sha} of {x['sha256_of']} |")
    out += ["", "Citations:", ""] + [f"- {x['citation']}" for x in t["sources"]] + [""]
    return "\n".join(out)


def anchor(r) -> str:
    """The anchor a Markdown renderer gives the heading of a rung."""
    import re
    return re.sub(r"[^a-z0-9 _-]", "", f"{r['rung']}. {r['title']}".lower()).replace(" ", "-")
